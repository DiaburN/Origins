-- -----------------------------------------------------------------------------
-- Zircon SetInfo / SetInfoStat equivalent. Imported Crystal ItemSet membership is
-- stored here; future ORIGINS sets use the same tables.
-- -----------------------------------------------------------------------------
CREATE TABLE content.item_set_definitions (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_key            varchar(160) NOT NULL UNIQUE,
    set_name            varchar(160) NOT NULL,
    class_id            smallint REFERENCES content.class_definitions(id) ON DELETE SET NULL,
    source_system       varchar(32) NOT NULL,
    source_set_id       integer,
    source_repo         text,
    source_path         text,
    source_commit       varchar(64),
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE content.item_set_members (
    item_set_id         bigint NOT NULL REFERENCES content.item_set_definitions(id) ON DELETE CASCADE,
    item_definition_id  bigint NOT NULL REFERENCES content.item_definitions(id) ON DELETE CASCADE,
    PRIMARY KEY (item_set_id,item_definition_id)
);

-- Future set bonuses are supported but no bonus is fabricated during Crystal
-- import. Flat item stats remain exactly as stored in source.
CREATE TABLE content.item_set_bonuses (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_set_id         bigint NOT NULL REFERENCES content.item_set_definitions(id) ON DELETE CASCADE,
    pieces_required     integer NOT NULL,
    class_id            smallint REFERENCES content.class_definitions(id) ON DELETE CASCADE,
    stat_code           varchar(64),
    amount              numeric(18,6),
    buff_definition_id  bigint REFERENCES content.buff_definitions(id) ON DELETE SET NULL,
    effect_key          varchar(160),
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,
    CHECK (pieces_required > 0),
    CHECK (stat_code IS NOT NULL OR buff_definition_id IS NOT NULL OR effect_key IS NOT NULL)
);
CREATE INDEX item_set_bonuses_set_idx ON content.item_set_bonuses(item_set_id,pieces_required);

-- Item-triggered buffs/effects use Zircon-style runtime logic. Empty at import
-- unless the source explicitly defines an effect; later ORIGINS items can reuse it.
CREATE TABLE content.item_buff_effects (
    item_definition_id  bigint NOT NULL REFERENCES content.item_definitions(id) ON DELETE CASCADE,
    buff_definition_id  bigint NOT NULL REFERENCES content.buff_definitions(id) ON DELETE CASCADE,
    trigger_type        varchar(32) NOT NULL DEFAULT 'equipped',
    stack_mode          varchar(32) NOT NULL DEFAULT 'replace',
    magnitude           numeric(18,6),
    duration_ms         bigint,
    source_system       varchar(32) NOT NULL DEFAULT 'zircon',
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (item_definition_id,buff_definition_id,trigger_type),
    CHECK (trigger_type IN ('equipped','use','hit','struck','kill','low_hp','passive')),
    CHECK (stack_mode IN ('replace','stack','refresh','ignore')),
    CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

COMMIT;
