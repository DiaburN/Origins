-- Convenience view used by runtime/importer QA. One row per item/class/stat,
-- preferring the class-specific overlay and otherwise inheriting base stats.
CREATE VIEW content.effective_item_stats AS
SELECT
    i.id AS item_definition_id,
    c.id AS class_id,
    c.code AS class_code,
    base.stat_code,
    CASE
        WHEN overlay.mode = 'replace' THEN overlay.amount
        WHEN overlay.mode = 'add' THEN base.amount + overlay.amount
        WHEN overlay.mode = 'multiply' THEN base.amount * overlay.amount
        ELSE base.amount
    END AS amount,
    COALESCE(overlay.source_system, i.source_system, 'origins') AS effective_source
FROM content.item_definitions i
CROSS JOIN content.class_definitions c
JOIN content.item_stats base
  ON base.item_definition_id = i.id
LEFT JOIN content.item_class_stats overlay
  ON overlay.item_definition_id = i.id
 AND overlay.class_id = c.id
 AND overlay.stat_code = base.stat_code
UNION ALL
SELECT
    i.id,
    c.id,
    c.code,
    overlay.stat_code,
    overlay.amount,
    overlay.source_system
FROM content.item_definitions i
JOIN content.item_class_stats overlay
  ON overlay.item_definition_id = i.id
JOIN content.class_definitions c
  ON c.id = overlay.class_id
WHERE NOT EXISTS (
    SELECT 1
    FROM content.item_stats base
    WHERE base.item_definition_id = i.id
      AND base.stat_code = overlay.stat_code
);

COMMIT;
